// Builds src/core/common-words.ts: ordinary Turkish words that are also a
// one-word name in the catalog ("Halı", "Bahar", "Dağ"). At the start of a
// sentence such a word is not taken for a person without other evidence.
//
// Usage: node scripts/common-words.mjs <words.txt>
// <words.txt>: one Turkish word per line, e.g. the Vikisözlük list collected
// by https://github.com/mertemin/turkish-word-list (CC BY-SA 3.0). Only the
// overlap with the catalog's one-word names is kept, as normalized keys.
import { readFileSync, writeFileSync } from "node:fs";
import { build } from "esbuild";

const source = process.argv[2];
if (!source) throw new Error("Usage: node scripts/common-words.mjs <words.txt>");

// The core is TypeScript: bundle the two helpers needed for this run.
const out = new URL("../dist/common-words-helper.mjs", import.meta.url);
await build({
  stdin: {
    contents: 'export { Catalog, NameIndex, nameKey } from "./src/core/index.js";',
    resolveDir: new URL("..", import.meta.url).pathname,
    loader: "ts",
  },
  bundle: true,
  platform: "node",
  format: "esm",
  outfile: out.pathname,
  logLevel: "error",
});
const { Catalog, NameIndex, nameKey } = await import(out.href);

const catalog = Catalog.fromCsv(readFileSync(new URL("../data/catalog.csv", import.meta.url), "utf8"));
const index = new NameIndex(catalog.people);
const words = readFileSync(source, "utf8")
  .split(/\r?\n/)
  .map((w) => w.trim())
  .filter((w) => w.length >= 3 && !/[\s\d]/.test(w));
const keys = new Set();
for (const word of words) {
  const key = nameKey(word);
  if (key.length >= 3 && index.has(key)) keys.add(key);
}
const sorted = [...keys].sort();
const lines = [];
for (let k = 0; k < sorted.length; k += 12) lines.push("  " + sorted.slice(k, k + 12).map((w) => JSON.stringify(w)).join(", ") + ",");
writeFileSync(
  new URL("../src/core/common-words.ts", import.meta.url),
  `/**
 * Ordinary Turkish words that are also a one-word name in the catalog, as
 * normalized keys ("hali" for "halı", "bahar", "dag"). Generated by
 * scripts/common-words.mjs from the Vikisözlük word list (CC BY-SA 3.0,
 * https://tr.wiktionary.org); do not edit by hand.
 */
export const COMMON_WORDS = new Set<string>([
${lines.join("\n")}
]);
`,
);
console.log(`${sorted.length} common words`);
